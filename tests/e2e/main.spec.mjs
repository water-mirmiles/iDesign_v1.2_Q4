import { test, expect } from '@playwright/test';
test('project, theme, library and board navigation has no missing resources', async ({ page }) => {
  const failures = [];
  page.on('pageerror', e => failures.push(e.message));
  page.on('response', r => { if (r.status() >= 400) failures.push(`${r.status()} ${r.url()}`); });
  await page.goto('./');
  await expect(page.getByText('暂无数据，')).toBeVisible();
  await page.locator('[data-action="tab"][data-tab="self"]').click();
  await expect(page.getByLabel('打开项目 AS 演示', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: '切换深浅色主题' }).click();
  await page.reload();
  await expect(page.locator('body')).toHaveClass('dark');
  await page.getByRole('button', { name: '全球产品库', exact: true }).click();
  await page.locator('[data-action="product-detail"][data-id="mango"]').click();
  await expect(page.getByRole('heading', { name: 'Round-toe leather heeled ankle boots' })).toBeVisible();
  await page.getByRole('button', { name: '看板', exact: true }).click();
  await expect(page.getByText('经营目标总览', { exact: true })).toBeVisible();
  expect(failures).toEqual([]);
});
test('new project persists nodes, explicit demo generation and JSON backup', async ({ page }) => {
  await page.goto('./');
  await page.locator('.header').getByRole('button', { name: '新建项目', exact: true }).click();
  await page.getByLabel('项目名称', { exact: true }).fill('CI 回归工程');
  await page.getByRole('button', { name: '创建并进入画布' }).click();
  await expect(page.getByLabel('无限画布')).toBeVisible();
  await page.getByRole('button', { name: '打开节点工具' }).click();
  await page.getByRole('button', { name: '自由创作', exact: true }).click();
  await page.getByRole('textbox', { name: '设计描述', exact: true }).fill('保留鞋型，测试演示变化');
  await page.getByRole('button', { name: '生成', exact: true }).click();
  await expect(page.locator('.result-label')).toContainText('演示');
  await page.reload();
  await expect(page.locator('.result-label')).toContainText('演示');
  await page.getByRole('button', { name: '导出', exact: true }).click();
  const download = page.waitForEvent('download');
  await page.getByRole('button', { name: '导出项目文件 (.json)' }).click();
  const file = await download;
  expect(file.suggestedFilename()).toBe('idesign-project.json');
  const stream = await file.createReadStream();
  let body = ''; for await (const chunk of stream) body += chunk;
  const backup = JSON.parse(body);
  expect(backup.project.name).toBe('CI 回归工程');
  expect(backup.nodes).toHaveLength(1);
});
